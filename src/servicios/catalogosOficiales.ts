// Valores conformes para cálculo de puntaje institucional
export const COMPLIANT_VALUES = new Set([
  'Cumple',
  'Limpios',
  'Sí',
  'Existe',
  'Funciona',
  'Funcionando',
  'Libre de objetos ajenos',
  'CO₂',
  'Sin Alarmas',
  'Automático',
]);

// Valores neutros excluidos del puntaje
export const NEUTRAL_VALUES = new Set(['No Aplica']);

// Evalúa si una pregunta es visible de acuerdo con las respuestas previas
export function evaluarVisibilidad(
  pregunta: PreguntaEvaluacion,
  respuestas: Record<string, RespuestaCriterio>
): boolean {
  if (!pregunta.visibleIf) return true;
  const respPadre = respuestas[pregunta.visibleIf.question]?.valor;
  if (pregunta.visibleIf.operator === 'equals') {
    return respPadre === pregunta.visibleIf.value;
  }
  return true;
}

// Cálculo institucional de avance y calificación de cumplimiento
export function calcularMetricasEvaluacion(
  respuestas: Record<string, RespuestaCriterio>,
  listaPreguntas: PreguntaEvaluacion[] = questions
): MetricasEvaluacion {
  // 1. Filtrar preguntas que son visibles en base a las respuestas actuales
  const preguntasVisibles = listaPreguntas.filter((p) =>
    evaluarVisibilidad(p, respuestas)
  );

  let totalRespondidos = 0;
  let totalCumple = 0;
  let totalNoCumple = 0;
  let totalNoAplica = 0;

  let puntosObtenidos = 0;
  let puntosPosibles = 0;

  for (const p of preguntasVisibles) {
    const resp = respuestas[p.id];
    const valor = resp?.valor?.trim();

    if (valor !== undefined && valor !== '') {
      totalRespondidos++;

      if (NEUTRAL_VALUES.has(valor)) {
        totalNoAplica++;
      } else if (COMPLIANT_VALUES.has(valor)) {
        totalCumple++;
        if (p.peso > 0) {
          puntosObtenidos += p.peso;
          puntosPosibles += p.peso;
        }
      } else {
        // No conforme
        if (p.peso > 0) {
          totalNoCumple++;
          puntosPosibles += p.peso;
        }
      }
    } else {
      // No respondido aún: si tiene peso, contribuye a los puntos posibles
      if (p.peso > 0) {
        puntosPosibles += p.peso;
      }
    }
  }

  // Preguntas requeridas visibles
  const preguntasRequeridas = preguntasVisibles.filter((p) => p.required);
  const requeridasRespondidas = preguntasRequeridas.filter(
    (p) => respuestas[p.id]?.valor !== undefined && respuestas[p.id]?.valor !== ''
  );

  const porcentajeAvance =
    preguntasRequeridas.length > 0
      ? Math.round((requeridasRespondidas.length / preguntasRequeridas.length) * 100)
      : preguntasVisibles.length > 0
      ? Math.round((totalRespondidos / preguntasVisibles.length) * 100)
      : 0;

  const calificacionCumplimiento =
    puntosPosibles > 0 ? Math.round((puntosObtenidos / puntosPosibles) * 100) : 100;

  return {
    totalCriterios: preguntasVisibles.length,
    totalRespondidos,
    totalCumple,
    totalNoCumple,
    totalNoAplica,
    porcentajeAvance,
    calificacionCumplimiento,
  };
}


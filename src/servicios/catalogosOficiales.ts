/**
 * Obtiene los cuartos registrados para una unidad específica por su ID.
 * Si la unidad no tiene cuartos registrados en catálogo, devuelve MDF e IDF por defecto.
 */
export function obtenerCuartosPorUnidad(unitId: number): Cuarto[] {
  const encontrados = rooms.filter((r) => r.unitId === unitId);
  if (encontrados.length > 0) {
    return encontrados;
  }
  return [
    { id: `ID${unitId}MDF`, unitId, nombre: 'MDF' },
    { id: `ID${unitId}IDF`, unitId, nombre: 'IDF' },
  ];
}
